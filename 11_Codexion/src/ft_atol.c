#include "codexion.h"

long	ft_atol(char *s)
{
	long	r;
	int		i;

	r = 0;
	i = 0;
	while (s[i])
	{
		if (s[i] < '0' || s[i] > '9')
			return (-1);
		r = r * 10 + s[i] - '0';
		if (r > 2147483647)
			return (-1);
		i++;
	}
	return (r);
}
